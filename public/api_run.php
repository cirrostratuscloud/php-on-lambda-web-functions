<?php
/**
 * Interactive demo runner for the dashboard playground.
 *
 * SECURITY: this NEVER evaluates user input as code. `demo` selects a fixed
 * handler from a hardcoded allowlist; `arg` is passed only as DATA to that
 * handler. There is no eval(), no dynamic function calls from user input, and
 * no shelling out. The worst a caller can do is feed a string to a hash/date/
 * json/uuid/image routine.
 */

$demo = $_GET['demo'] ?? '';
$arg  = (string)($_GET['arg'] ?? '');

// Cap input size so no demo can be abused for CPU/memory blowups.
if (strlen($arg) > 4096) {
    $arg = substr($arg, 0, 4096);
}

switch ($demo) {

    case 'hash':
        json_out([
            'input'  => $arg,
            'length' => strlen($arg),
            'md5'    => md5($arg),
            'sha256' => hash('sha256', $arg),
            'crc32'  => sprintf('%u', crc32($arg)),
        ]);
        break;

    case 'date':
        // Treat arg as a date expression; default to now. Add 90 days as a demo.
        try {
            $base = ($arg === '' ) ? new DateTimeImmutable('now', new DateTimeZone('UTC'))
                                   : new DateTimeImmutable($arg, new DateTimeZone('UTC'));
            $plus = $base->add(new DateInterval('P90D'));
            json_out([
                'parsed_utc'       => $base->format(DateTimeInterface::ATOM),
                'plus_90_days_utc' => $plus->format(DateTimeInterface::ATOM),
                'day_of_week'      => $base->format('l'),
                'unix'             => (int)$base->format('U'),
            ]);
        } catch (Throwable $e) {
            json_out(['error' => 'Could not parse as a date: ' . $arg], 400);
        }
        break;

    case 'json':
        $decoded = json_decode($arg, true);
        if (json_last_error() !== JSON_ERROR_NONE) {
            json_out([
                'valid' => false,
                'error' => json_last_error_msg(),
                'hint'  => 'Enter valid JSON in the input box, e.g. {"a":1,"b":[2,3]}',
            ], 400);
        }
        json_out([
            'valid'  => true,
            'type'   => gettype($decoded),
            'pretty' => json_encode($decoded, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES),
        ]);
        break;

    case 'uuid':
        json_out([
            'uuid_v4' => uuid_v4(),
            'note'    => 'Generated with random_bytes() (CSPRNG).',
        ]);
        break;

    case 'image':
        render_image($arg);
        break;

    default:
        json_out(['error' => 'Unknown demo. Allowed: hash, date, json, uuid, image.'], 400);
}

// ---------------------------------------------------------------------------

function json_out(array $data, int $status = 200): void
{
    http_response_code($status);
    header('Content-Type: application/json');
    echo json_encode($data, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES);
    exit;
}

function uuid_v4(): string
{
    $b = random_bytes(16);
    $b[6] = chr((ord($b[6]) & 0x0f) | 0x40); // version 4
    $b[8] = chr((ord($b[8]) & 0x3f) | 0x80); // variant
    return vsprintf('%s%s-%s-%s-%s-%s%s%s', str_split(bin2hex($b), 4));
}

/**
 * Render a small generated image. Uses gd if available, otherwise emits an
 * SVG built as a string — so the demo works on any build.
 */
function render_image(string $text): void
{
    $text = $text === '' ? 'PHP on Lambda' : $text;
    $text = mb_substr($text, 0, 40);

    // Deterministic colour from the input.
    $seed = crc32($text);
    $h1 = $seed % 360;
    $h2 = ($seed >> 3) % 360;

    if (extension_loaded('gd')) {
        $w = 480; $hgt = 200;
        $im = imagecreatetruecolor($w, $hgt);
        [$r1,$g1,$b1] = hsl_to_rgb($h1, 70, 45);
        [$r2,$g2,$b2] = hsl_to_rgb($h2, 70, 35);
        // vertical gradient
        for ($y = 0; $y < $hgt; $y++) {
            $t = $y / $hgt;
            $c = imagecolorallocate(
                $im,
                (int)($r1 + ($r2 - $r1) * $t),
                (int)($g1 + ($g2 - $g1) * $t),
                (int)($b1 + ($b2 - $b1) * $t)
            );
            imageline($im, 0, $y, $w, $y, $c);
        }
        $white = imagecolorallocate($im, 255, 255, 255);
        imagestring($im, 5, 18, 14, 'Generated by gd', $white);
        imagestring($im, 5, 18, 90, $text, $white);
        header('Content-Type: image/png');
        imagepng($im);
        imagedestroy($im);
        exit;
    }

    // SVG fallback (no gd needed).
    $safe = htmlspecialchars($text, ENT_QUOTES);
    header('Content-Type: image/svg+xml');
    echo <<<SVG
<svg xmlns="http://www.w3.org/2000/svg" width="480" height="200" viewBox="0 0 480 200">
  <defs>
    <linearGradient id="g" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="hsl({$h1},70%,45%)"/>
      <stop offset="1" stop-color="hsl({$h2},70%,35%)"/>
    </linearGradient>
  </defs>
  <rect width="480" height="200" rx="16" fill="url(#g)"/>
  <text x="24" y="40" font-family="system-ui" font-size="15" fill="#ffffffcc">Generated by PHP (SVG fallback — no gd)</text>
  <text x="24" y="118" font-family="system-ui" font-size="34" font-weight="700" fill="#fff">{$safe}</text>
</svg>
SVG;
    exit;
}

function hsl_to_rgb(float $h, float $s, float $l): array
{
    $s /= 100; $l /= 100;
    $c = (1 - abs(2 * $l - 1)) * $s;
    $x = $c * (1 - abs(fmod($h / 60, 2) - 1));
    $m = $l - $c / 2;
    [$r,$g,$b] = match (true) {
        $h < 60  => [$c, $x, 0],
        $h < 120 => [$x, $c, 0],
        $h < 180 => [0, $c, $x],
        $h < 240 => [0, $x, $c],
        $h < 300 => [$x, 0, $c],
        default  => [$c, 0, $x],
    };
    return [(int)(($r + $m) * 255), (int)(($g + $m) * 255), (int)(($b + $m) * 255)];
}
